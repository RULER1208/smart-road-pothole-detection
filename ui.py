def ensure_rgb(image: np.ndarray) -> np.ndarray:
    array = np.asarray(image)
    if array.ndim == 2:
        array = cv2.cvtColor(array, cv2.COLOR_GRAY2RGB)
    elif array.shape[-1] == 4:
        array = cv2.cvtColor(array, cv2.COLOR_RGBA2RGB)
    if array.dtype != np.uint8:
        array = np.clip(array, 0, 255).astype(np.uint8)
    return np.ascontiguousarray(array)


def run_inference(
    image_rgb: np.ndarray,
    model_name: str,
    confidence: float,
) -> Tuple[List[Dict[str, Any]], float]:
    """Returns (detections, latency_ms). Timer covers the same work for all models."""
    import torch

    model = load_model(model_name)
    device = get_device()
    detections: List[Dict[str, Any]] = []

    if model_name == "YOLOv8n":
        # Ultralytics expects BGR for numpy input
        image_bgr = np.ascontiguousarray(image_rgb[:, :, ::-1])
        if device.type == "cuda":
            torch.cuda.synchronize()
        start = time.perf_counter()
        result = model.predict(
            source=image_bgr, conf=float(confidence), iou=0.45,
            imgsz=640, verbose=False,
        )[0]
        if device.type == "cuda":
            torch.cuda.synchronize()
        latency_ms = (time.perf_counter() - start) * 1000

        if result.boxes is not None and len(result.boxes):
            for box, score in zip(
                result.boxes.xyxy.cpu().numpy(),
                result.boxes.conf.cpu().numpy(),
            ):
                detections.append(
                    {"box": [float(v) for v in box], "score": float(score)}
                )
        return detections, latency_ms

    from torchvision.transforms.functional import to_tensor

    if device.type == "cuda":
        torch.cuda.synchronize()
    start = time.perf_counter()
    tensor = to_tensor(image_rgb).to(device)
    with torch.inference_mode():
        output = model([tensor])[0]
    if device.type == "cuda":
        torch.cuda.synchronize()
    latency_ms = (time.perf_counter() - start) * 1000

    boxes = output["boxes"].cpu().numpy()
    scores = output["scores"].cpu().numpy()
    labels = output["labels"].cpu().numpy()
    for box, score, label in zip(boxes, scores, labels):
        if float(score) >= float(confidence) and int(label) == 1:
            detections.append(
                {"box": [float(v) for v in box], "score": float(score)}
            )
    return detections, latency_ms


def enrich(
    detection: Dict[str, Any],
    shape: Tuple[int, int, int],
    pixels_per_cm: float,
    large_percent: float,
    large_cm2: float,
) -> Dict[str, Any]:
    """Adds size measurements and a severity tier to one detection."""
    height, width = shape[:2]
    x1, y1, x2, y2 = detection["box"]
    x1 = max(0.0, min(width - 1.0, x1))
    y1 = max(0.0, min(height - 1.0, y1))
    x2 = max(0.0, min(float(width), x2))
    y2 = max(0.0, min(float(height), y2))

    box_w, box_h = max(0.0, x2 - x1), max(0.0, y2 - y1)
    area_percent = 100.0 * (box_w * box_h) / max(1.0, width * height)

    ppc = float(pixels_per_cm or 0.0)
    calibrated = ppc > 0
    width_cm = box_w / ppc if calibrated else None
    height_cm = box_h / ppc if calibrated else None
    area_cm2 = (width_cm * height_cm) if calibrated else None

    threshold = float(large_cm2) if calibrated else float(large_percent)
    measure = area_cm2 if calibrated else area_percent
    if measure >= threshold:
        severity = "large"
    elif measure >= threshold / 2:
        severity = "medium"
    else:
        severity = "small"

    out = dict(detection)
    out.update({
        "box": [x1, y1, x2, y2],
        "box_width_px": box_w, "box_height_px": box_h,
        "area_percent": area_percent, "calibrated": calibrated,
        "width_cm": width_cm, "height_cm": height_cm, "area_cm2": area_cm2,
        "severity": severity, "is_large": severity == "large",
    })
    return out


def draw_label(canvas, text, x, y, rgb):
    font = cv2.FONT_HERSHEY_SIMPLEX
    (tw, th), base = cv2.getTextSize(text, font, 0.52, 1)
    x = max(0, min(canvas.shape[1] - tw - 10, int(x)))
    y = max(th + base + 8, int(y))
    cv2.rectangle(canvas, (x, y - th - base - 7), (x + tw + 10, y + 1), rgb, -1)
    cv2.putText(canvas, text, (x + 5, y - base - 1), font, 0.52,
                (255, 255, 255), 1, cv2.LINE_AA)


def annotate(
    image_rgb: np.ndarray,
    detections: List[Dict[str, Any]],
    model_name: str,
    latency_ms: float,
) -> np.ndarray:
    canvas = image_rgb.copy()
    height, width = canvas.shape[:2]

    for index, det in enumerate(detections, start=1):
        x1, y1, x2, y2 = [int(round(v)) for v in det["box"]]
        rgb = SEVERITY_RGB[det["severity"]]
        cv2.rectangle(canvas, (x1, y1), (x2, y2), rgb,
                      4 if det["is_large"] else 2)
        if det["calibrated"]:
            size_text = f"{det['width_cm']:.0f}x{det['height_cm']:.0f}cm"
        else:
            size_text = f"{det['area_percent']:.1f}%"
        draw_label(canvas, f"#{index} {det['score']:.2f} | {size_text} | "
                           f"{det['severity'].upper()}", x1, max(24, y1), rgb)

    draw_label(canvas, f"{model_name} | {len(detections)} pothole(s) | "
                       f"{latency_ms:.1f} ms", 8, height - 10, (30, 41, 59))

    large = sum(d["is_large"] for d in detections)
    if large:
        bar = max(40, int(height * .07))
        overlay = canvas.copy()
        cv2.rectangle(overlay, (0, 0), (width, bar), SEVERITY_RGB["large"], -1)
        cv2.addWeighted(overlay, .85, canvas, .15, 0, canvas)
        cv2.putText(canvas, f"WARNING: {large} LARGE POTHOLE(S)",
                    (14, int(bar * .68)), cv2.FONT_HERSHEY_SIMPLEX,
                    max(.6, min(1.05, width / 950)), (255, 255, 255), 2,
                    cv2.LINE_AA)
    return canvas


def rows_from(detections, model_name, latency_ms) -> List[Dict[str, Any]]:
    rows = []
    for index, det in enumerate(detections, start=1):
        x1, y1, x2, y2 = det["box"]
        rows.append({
            "Model": model_name,
            "No.": index,
            "Confidence": round(det["score"], 4),
            "X1": round(x1, 1), "Y1": round(y1, 1),
            "X2": round(x2, 1), "Y2": round(y2, 1),
            "Width (px)": round(det["box_width_px"], 1),
            "Height (px)": round(det["box_height_px"], 1),
            "Area (% frame)": round(det["area_percent"], 3),
            "Width (cm)": None if det["width_cm"] is None else round(det["width_cm"], 1),
            "Height (cm)": None if det["height_cm"] is None else round(det["height_cm"], 1),
            "Area (cm2)": None if det["area_cm2"] is None else round(det["area_cm2"], 1),
            "Severity": det["severity"].capitalize(),
            "Large": "YES" if det["is_large"] else "No",
            "Latency (ms)": round(latency_ms, 2),
        })
    return rows


