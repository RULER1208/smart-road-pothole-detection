@st.cache_resource(show_spinner=False)
def get_device():
    import torch
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


@st.cache_resource(show_spinner=False)
def load_model(model_name: str):
    """Load and cache one detector. Raises FileNotFoundError with a clear message."""
    import torch
    from torchvision.models.detection import (
        fasterrcnn_resnet50_fpn,
        ssd300_vgg16,
    )

    path = MODEL_FILES[model_name]
    if not path.is_file():
        raise FileNotFoundError(
            f"Checkpoint for {model_name} not found at: {path}\n"
            f"Place the file there, or set POTHOLE_MODELS_DIR."
        )

    device = get_device()

    if model_name == "YOLOv8n":
        from ultralytics import YOLO
        return YOLO(str(path))

    if model_name == "SSD300-VGG16":
        model = ssd300_vgg16(weights=None, weights_backbone=None, num_classes=2)
    else:
        # min_size = max_size = 640 matches the training configuration exactly
        model = fasterrcnn_resnet50_fpn(
            weights=None, weights_backbone=None, num_classes=2,
            min_size=640, max_size=640,
        )

    checkpoint = torch.load(str(path), map_location="cpu", weights_only=False)
    state = checkpoint
    if isinstance(checkpoint, dict):
        for key in ("model_state_dict", "state_dict", "model"):
            value = checkpoint.get(key)
            if isinstance(value, dict):
                state = value
                break
            if hasattr(value, "state_dict"):
                state = value.state_dict()
                break
    if all(k.startswith("module.") for k in state):
        state = {k[7:]: v for k, v in state.items()}

    model.load_state_dict(state, strict=True)
    model.to(device).eval()
    return model


def checkpoint_status() -> Dict[str, bool]:
    return {name: path.is_file() for name, path in MODEL_FILES.items()}


