def tab_video(cfg: Dict[str, Any]) -> None:
    upload = st.file_uploader(
        "Upload a road video", type=["mp4", "mov", "avi", "mkv"], key="video_upload"
    )

    controls = st.columns(3)
    stride = controls[0].slider("Analyse every Nth frame", 1, 10, 2)
    max_seconds = controls[1].number_input("Max seconds (0 = full)", 0.0, 600.0, 15.0, 5.0)
    line_fraction = controls[2].slider("Counting line (frame height)", 0.30, 0.90, 0.65, 0.05)

    if upload is None:
        st.info("Upload a road video to start analysis.")
        return
    if not st.button("Process video", key="detect_video"):
        return
    if not cfg["ready"]:
        st.error("No model checkpoints available.")
        return

    model_name = (cfg["ready"][0] if cfg["model_choice"] == "Compare all models"
                  else cfg["model_choice"])

    temp_dir = Path("temp_uploads")
    temp_dir.mkdir(exist_ok=True)
    input_path = temp_dir / f"in_{uuid.uuid4().hex[:8]}.mp4"
    input_path.write_bytes(upload.getvalue())

    capture = cv2.VideoCapture(str(input_path))
    if not capture.isOpened():
        st.error("Could not open the uploaded video.")
        return

    fps = capture.get(cv2.CAP_PROP_FPS) or 25.0
    width = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
    limit = int(max_seconds * fps) if max_seconds > 0 else total
    limit = min(limit, total) if total > 0 else limit
    line_y = int(height * line_fraction)

    output_path = temp_dir / f"out_{uuid.uuid4().hex[:8]}.mp4"
    writer = cv2.VideoWriter(str(output_path), cv2.VideoWriter_fourcc(*"mp4v"),
                             fps, (width, height))

    tracks: Dict[int, Dict[str, Any]] = {}
    next_id = 1
    unique_total = unique_large = 0
    counted: List[Tuple[int, float, str]] = []
    rows: List[Dict[str, Any]] = []
    last: List[Dict[str, Any]] = []
    last_ids: List[int] = []
    last_latency = 0.0
    first_time: Optional[float] = None

    progress = st.progress(0.0, text="Starting…")
    preview = st.empty()
    frame_index = 0

    def iou(a, b) -> float:
        ax1, ay1, ax2, ay2 = a
        bx1, by1, bx2, by2 = b
        ix1, iy1 = max(ax1, bx1), max(ay1, by1)
        ix2, iy2 = min(ax2, bx2), min(ay2, by2)
        inter = max(0.0, ix2 - ix1) * max(0.0, iy2 - iy1)
        union = (ax2 - ax1) * (ay2 - ay1) + (bx2 - bx1) * (by2 - by1) - inter
        return inter / union if union > 0 else 0.0

    while frame_index < limit:
        ok, frame_bgr = capture.read()
        if not ok:
            break
        frame_rgb = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2RGB)
        seconds = frame_index / fps

        if frame_index % stride == 0:
            try:
                detections, last_latency = run_inference(
                    frame_rgb, model_name, cfg["confidence"]
                )
            except Exception as error:          # noqa: BLE001
                st.error(f"{model_name} failed: {error}")
                break
            last = [
                enrich(d, frame_rgb.shape, cfg["pixels_per_cm"],
                       cfg["large_percent"], cfg["large_cm2"])
                for d in detections
            ]

            # --- greedy IoU tracking ---
            assigned: List[Optional[int]] = [None] * len(last)
            pairs = sorted(
                ((iou(t["box"], d["box"]), tid, i)
                 for tid, t in tracks.items() for i, d in enumerate(last)
                 if iou(t["box"], d["box"]) >= 0.3),
                reverse=True,
            )
            used_t, used_d = set(), set()
            for _, tid, i in pairs:
                if tid in used_t or i in used_d:
                    continue
                assigned[i] = tid
                used_t.add(tid)
                used_d.add(i)
            for i, det in enumerate(last):
                if assigned[i] is None:
                    assigned[i] = next_id
                    centre = 0.5 * (det["box"][1] + det["box"][3])
                    tracks[next_id] = {
                        "box": det["box"], "age": 0, "last_cy": centre,
                        "counted": False, "born_below": centre > line_y,
                        "rank": SEVERITY_RANK[det["severity"]],
                    }
                    next_id += 1
                    continue
                tid = assigned[i]
                track = tracks[tid]
                centre = 0.5 * (det["box"][1] + det["box"][3])
                track["age"] += 1
                track["box"] = det["box"]
                track["rank"] = max(track["rank"], SEVERITY_RANK[det["severity"]])
                crossed = track["last_cy"] <= line_y < centre
                if (not track["counted"] and not track["born_below"]
                        and track["age"] >= 3 and crossed):
                    track["counted"] = True
                    unique_total += 1
                    tier = "Large" if track["rank"] >= 2 else "Small/Medium"
                    if track["rank"] >= 2:
                        unique_large += 1
                    counted.append((tid, seconds, tier))
                track["last_cy"] = centre
            last_ids = [int(a) for a in assigned]

            if last and first_time is None:
                first_time = seconds
            for row in rows_from(last, model_name, last_latency):
                row["Time (s)"] = round(seconds, 2)
                row["Frame"] = frame_index
                rows.append(row)

        annotated = annotate(frame_rgb, last, model_name, last_latency)
        cv2.line(annotated, (0, line_y), (width, line_y), (56, 189, 248), 2)
        for det, tid in zip(last, last_ids):
            mark = " ✓" if tracks.get(tid, {}).get("counted") else ""
            draw_label(annotated, f"ID {tid}{mark}", det["box"][0],
                       min(height - 4, det["box"][3] + 20), (30, 41, 59))
        draw_label(annotated,
                   f"In frame {len(last)} | Unique {unique_total} | Large {unique_large}",
                   8, 26, (30, 41, 59))
        draw_label(annotated, f"t={seconds:05.1f}s", 8, height - 44, (30, 41, 59))

        writer.write(cv2.cvtColor(annotated, cv2.COLOR_RGB2BGR))

        if frame_index % max(1, int(fps)) == 0:
            preview.image(annotated, caption=f"Frame {frame_index}",
                          use_container_width=True)
            progress.progress(min(.99, frame_index / max(1, limit)),
                              text=f"Frame {frame_index} of {limit}")
        frame_index += 1

    capture.release()
    writer.release()
    progress.progress(1.0, text="Complete")
    progress.empty()
    preview.empty()

    cols = st.columns(4)
    cards = [
        ("Unique potholes", str(unique_total), "crossed counting line", None),
        ("Large potholes", str(unique_large), "unique, severity Large",
         SEVERITY_HEX["large"] if unique_large else None),
        ("First detected", "—" if first_time is None else f"{first_time:.1f}s",
         "earliest detection", None),
        ("Frames written", str(frame_index), f"{fps:.0f} fps source", None),
    ]
    for col, (label, value, sub, colour), step in zip(cols, cards, range(1, 5)):
        col.markdown(metric_card(label, value, sub, colour, step), unsafe_allow_html=True)

    if output_path.is_file():
        st.video(str(output_path))
        st.download_button(
            "Download annotated video",
            output_path.read_bytes(),
            file_name=output_path.name,
            mime="video/mp4",
        )

    if counted:
        st.markdown("#### Counting log")
        st.dataframe(
            pd.DataFrame(counted, columns=["Track ID", "Crossed at (s)", "Severity"]),
            use_container_width=True, hide_index=True,
        )

    if rows:
        frame = pd.DataFrame(rows)
        st.download_button(
            "Download frame-level detections (CSV)",
            frame.to_csv(index=False).encode("utf-8"),
            file_name=f"video_detections_{uuid.uuid4().hex[:8]}.csv",
            mime="text/csv",
        )

    st.caption(
        "Unique counting uses IoU tracking plus line crossing to avoid recounting "
        "the same pothole across frames. It is an estimate — camera shake, "
        "occlusion or a static camera can affect it."
    )


